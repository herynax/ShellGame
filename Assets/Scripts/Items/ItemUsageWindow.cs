namespace ShellGame.Items
{
    /// <summary>
    /// В какой момент хода предмет разрешено использовать игроку
    /// (см. ItemDefinition.UsageWindow).
    ///
    /// Значение по умолчанию — OwnTurnOnly: для всех существующих предметов
    /// это сохраняет прежнее поведение (использовать можно было только на
    /// своём ходу). AnyTurn открывает предметы, которые не требуют выбора
    /// напертка (хилка, крест, таблетки) — их можно применить и пока ходит
    /// противник, потому что выбор напертка они не отменяют.
    ///
    /// Предметы, которые сами выбирают наперток или открывают его шлюз
    /// (нож, молоток, монокль), остаются OwnTurnOnly: на ходу врага
    /// выбор напертка принадлежит врагу.
    /// </summary>
    public enum ItemUsageWindow
    {
        /// <summary>Только когда ход активной стороны — этого игрока.</summary>
        OwnTurnOnly = 0,

        /// <summary>Только когда ход активной стороны — противника.</summary>
        EnemyTurnOnly = 1,

        /// <summary>В любой момент, когда идёт ход.</summary>
        AnyTurn = 2,
    }
}
